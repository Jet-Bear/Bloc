pub fn t() -> &'static Textos {
    static ELEGIDO: OnceLock<&'static Textos> = OnceLock::new();
    // BLOC_IDIOMA (el identificador primario de Windows, en hexadecimal: 9 es inglés) lo ponen las capturas del README.
    let pedido = std::env::var("BLOC_IDIOMA").ok().and_then(|x| u16::from_str_radix(&x, 16).ok());
    ELEGIDO.get_or_init(|| match pedido.unwrap_or_else(|| unsafe { GetUserDefaultUILanguage() }) & 0x3FF {
        0x0A => &ES,
        0x0C => &FR,
        0x07 => &DE,
        0x10 => &IT,
        0x16 => &PT,
        0x19 => &RU,
        0x15 => &PL,
        0x1F => &TR,
        0x04 => &ZH,
        0x11 => &JA,
        0x12 => &KO,
        _ => &EN,
    })
}

/// La frase de un menú sin el &, el atajo ni los puntos suspensivos: para el título de un cuadro.
pub fn limpio(s: &str) -> String {
    s.split('\t').next().unwrap_or(s).replace('&', "").trim_end_matches(['.', '…']).to_string()
}

/// Una carpeta larga, con su principio (la unidad o el servidor y su carpeta compartida) y su final: «A:\…\CLIENTES\X».
pub fn acortar(carpeta: &str) -> String {
    const MAX: usize = 40;
    let partes: Vec<&str> = carpeta.split('\\').collect();
    let k = if carpeta.starts_with(r"\\") { 4 } else { 1 };
    if carpeta.chars().count() <= MAX || partes.len() <= k + 1 {
        return carpeta.to_string();
    }
    let con_cola = |n: usize| format!("{}\\…\\{}", partes[..k].join("\\"), partes[partes.len().saturating_sub(n).max(k)..].join("\\"));
    let dos = con_cola(2);
    if dos.chars().count() <= MAX { dos } else { con_cola(1) }
}

/// La ayuda de un botón, de su texto de menú: «Nombre (atajo)».
pub fn con_atajo(menu: &str) -> String {
    match menu.split('\t').nth(1) {
        Some(k) => format!("{} ({k})", limpio(menu)),
        None => limpio(menu),
    }
}

